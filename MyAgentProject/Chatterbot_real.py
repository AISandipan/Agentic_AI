xi,yi = 0,0

def clear_message():
    global yi
    yi = 0
    for widget in chat_bg.winfo_children():
        widget.destroy

def send_message():
    global yi
    user_input = user_entry.get()
    if user_input.strip().lower() == "clear":
        clear_message()
        user_entry.delete(0, 'end')
        return

    user = Label(chat_bg, height=1, width=64, bg="#A6A6A6", fg="black", text="You  " + user_input, font=("FiraCode Nerd Font", 12, "bold"), anchor='w')
    user.place(x=xi,y=yi)

    response = chatbot.get_response(user_input)
    bot = Label(chat_bg, height=1, width=64, bg='white', fg='black', text="ChatBot " + str(response), font=("FiraCode Nerd Font", 12, "bold"), anchor='w')
    bot.place(x=xi,y=yi + 25)

    yi = yi + 50
    user_entry.delete(0, 'end')


